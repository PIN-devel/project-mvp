    static String classify(String merchant) {
        String value = merchant == null ? "" : merchant.toLowerCase(Locale.ROOT);
        for (String[] rule : CATEGORY_RULES) {
            // Generic payment-provider keywords do not identify the underlying purchase.
            if ("기타".equals(rule[0])) continue;
            for (String keyword : rule[1].split(",")) {
                if (value.contains(keyword.toLowerCase(Locale.ROOT))) return rule[0];
            }
        }
        return null;
    }
